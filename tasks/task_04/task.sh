#!/usr/bin/env bash

# Перевірка кількості аргументів (має бути рівно 2)
if [ "$#" -ne 2 ]; then
    echo "Використання: task.sh ЖУРНАЛ N" >&2
    exit 2
fi

LOG="$1"
N="$2"

# Перевірка існування файлу журналу
if [ ! -f "$LOG" ]; then
    echo "Помилка: файл не існує" >&2
    exit 3
fi

# Перевірка, чи N є додатним цілим числом
if ! [[ "$N" =~ ^[1-9][0-9]*$ ]]; then
    echo "Помилка: N має бути додатним цілим" >&2
    exit 4
fi

# Якщо файл порожній
if [ ! -s "$LOG" ]; then
    exit 0
fi

# Підрахунок IP-адрес (перше поле), сортування за кількістю (спадання) та алфавітом
awk '{print $1}' "$LOG" | sort | uniq -c | awk '{print $1, $2}' | sort -k1,1nr -k2,2 | head -n "$N"
exit 0